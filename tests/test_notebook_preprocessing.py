"""Regression tests for the preprocessing contract produced by Step 1."""

from pathlib import Path

import pandas as pd
import pytest

from src.utils.parameter_encoding import ENCODED_COLUMNS


PROJECT_ROOT = Path(__file__).resolve().parents[1]
RAW_DATA_PATH = PROJECT_ROOT / "data" / "Telco_customer_churn.xlsx"
ENCODED_DATA_PATH = PROJECT_ROOT / "data" / "telco_full_encoded.csv"


@pytest.fixture(scope="module")
def raw_data() -> pd.DataFrame:
    """Load the source workbook used by the Step 1 notebook."""
    return pd.read_excel(RAW_DATA_PATH)


@pytest.fixture(scope="module")
def encoded_data() -> pd.DataFrame:
    """Load the encoded artifact generated by the Step 1 notebook."""
    return pd.read_csv(ENCODED_DATA_PATH)


def test_step1_output_has_expected_model_schema(encoded_data):
    metadata_columns = ["CustomerID", "Count", "Country", "State"]
    model_features = encoded_data.drop(columns=[*metadata_columns, "target"])

    assert list(model_features.columns) == ENCODED_COLUMNS
    assert encoded_data.shape[1] == len(ENCODED_COLUMNS) + len(metadata_columns) + 1
    assert "Churn Score" not in encoded_data.columns
    assert "Churn Label" not in encoded_data.columns
    assert "Churn Reason" not in encoded_data.columns
    assert "City" not in encoded_data.columns
    assert "Lat Long" not in encoded_data.columns


def test_step1_output_is_numeric_and_target_is_binary(encoded_data):
    model_features = encoded_data.drop(
        columns=["CustomerID", "Country", "State", "target"]
    )
    assert model_features.select_dtypes(exclude="number").empty
    assert set(encoded_data["target"].unique()) <= {0, 1}
    assert encoded_data["target"].notna().all()


def test_total_charges_is_numeric_and_zero_tenure_blanks_become_zero(
    raw_data, encoded_data
):
    expected_total_charges = (
        pd.to_numeric(raw_data["Total Charges"].astype(str).str.strip(), errors="coerce")
        .fillna(0)
    )

    pd.testing.assert_series_equal(
        encoded_data["Total Charges"],
        expected_total_charges,
        check_names=False,
        check_dtype=False,
    )
    assert (encoded_data.loc[raw_data["Tenure Months"].eq(0), "Total Charges"] == 0).all()


def test_city_frequency_encoding_matches_source_distribution(raw_data, encoded_data):
    expected_frequencies = raw_data["City"].value_counts(normalize=True)
    expected = raw_data["City"].map(expected_frequencies).rename("City_Frequency")

    pd.testing.assert_series_equal(
        encoded_data["City_Frequency"],
        expected,
        check_names=True,
        check_dtype=False,
    )


def test_one_hot_features_are_binary_and_reference_categories_are_zero(encoded_data):
    one_hot_columns = [
        column
        for column in ENCODED_COLUMNS
        if "_" in column and column not in {"City_Frequency"}
    ]

    for column in one_hot_columns:
        assert set(encoded_data[column].unique()) <= {0, 1}, column

    # These are the dropped reference categories from pd.get_dummies(drop_first=True).
    assert (encoded_data.loc[encoded_data["target"].notna(), "Gender_Male"] >= 0).all()
    assert (encoded_data["Internet Service_Fiber optic"] + encoded_data["Internet Service_No"] <= 1).all()


def test_step1_output_preserves_row_alignment(raw_data, encoded_data):
    assert len(raw_data) == len(encoded_data)
    assert encoded_data.index.equals(pd.RangeIndex(start=0, stop=len(raw_data)))
